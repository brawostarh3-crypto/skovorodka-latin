import { readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';

const folder = dirname(fileURLToPath(import.meta.url));
const source = JSON.parse(readFileSync(join(folder, 'lexicon.json'), 'utf8'));
const sqlitePath = join(folder, 'lexicon.sqlite');
const scriptPath = join(folder, '..', 'assets', 'lexicon.js');
const tempSqlite = sqlitePath + '.tmp';
const tempScript = scriptPath + '.tmp';
const database = new DatabaseSync(':memory:');
const validWord = /^[a-z]+$/;
const topicIds = new Set(source.topics.map(({ id }) => id));
const sourceIds = new Set(source.sources.map(({ id }) => id));
const validGroups = new Set(['vowel', 'b', 'a', 'consonant']);

if (source.version !== 1) throw new Error('Unsupported lexicon format');
for (const reference of source.sources) {
  if (new URL(reference.url).protocol !== 'https:') throw new Error('Invalid source URL');
}
for (const term of source.terms) {
  if (!validWord.test(term.nom) || !validWord.test(term.gen) || !term.gen.endsWith('is') ||
      term.gen.length < 4 || !['m', 'f', 'n'].includes(term.gender) || !term.translation?.trim() ||
      !validGroups.has(term.group) || !topicIds.has(term.topic) ||
      (term.source && !sourceIds.has(term.source)) ||
      (term.genPlural && (!term.source || !validWord.test(term.genPlural)))) {
    throw new Error('Invalid term: ' + JSON.stringify(term));
  }
}
for (const group of validGroups) {
  if (source.terms.filter(term => term.group === group).length < 2) {
    throw new Error('The quiz needs at least two articles for group ' + group);
  }
}

database.exec(`
  PRAGMA foreign_keys = ON;
  PRAGMA user_version = 1;
  CREATE TABLE topics (id TEXT PRIMARY KEY NOT NULL, name TEXT NOT NULL) STRICT;
  CREATE TABLE sources (
    id TEXT PRIMARY KEY NOT NULL, title TEXT NOT NULL,
    publication TEXT NOT NULL, url TEXT NOT NULL
  ) STRICT;
  CREATE TABLE terms (
    id TEXT PRIMARY KEY NOT NULL,
    nominative TEXT NOT NULL, genitive TEXT NOT NULL,
    gender TEXT NOT NULL CHECK (gender IN ('m', 'f', 'n')),
    translation TEXT NOT NULL,
    declension_group TEXT NOT NULL CHECK (declension_group IN ('vowel', 'a', 'b', 'consonant')),
    topic_id TEXT NOT NULL REFERENCES topics(id),
    stem TEXT GENERATED ALWAYS AS (substr(genitive, 1, length(genitive) - 2)) STORED,
    genitive_plural TEXT,
    source_id TEXT REFERENCES sources(id),
    source_locator TEXT,
    note TEXT,
    UNIQUE (nominative, genitive, gender)
  ) STRICT;
  CREATE INDEX terms_nominative ON terms(nominative);
  CREATE INDEX terms_genitive ON terms(genitive);
  CREATE INDEX terms_topic_group ON terms(topic_id, declension_group);
`);

const addTopic = database.prepare('INSERT INTO topics VALUES (?, ?)');
const addSource = database.prepare('INSERT INTO sources VALUES (?, ?, ?, ?)');
const addTerm = database.prepare(`
  INSERT INTO terms (
    id, nominative, genitive, gender, translation, declension_group,
    topic_id, genitive_plural, source_id, source_locator, note
  ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
`);
database.exec('BEGIN');
for (const topic of source.topics) addTopic.run(topic.id, topic.name);
for (const item of source.sources) addSource.run(item.id, item.title, item.publication, item.url);
for (const term of source.terms) {
  addTerm.run(
    term.nom + '/' + term.gen + '/' + term.gender,
    term.nom, term.gen, term.gender, term.translation, term.group, term.topic,
    term.genPlural ?? null, term.source ?? null, term.locator ?? null, term.note ?? null
  );
}
database.exec('COMMIT');

const entries = database.prepare('SELECT * FROM terms ORDER BY rowid').all().map(term => [
  term.nominative, term.genitive, term.gender, term.translation, term.declension_group, {
    id: term.id, topic: term.topic_id, stem: term.stem, genPlural: term.genitive_plural,
    source: term.source_id, locator: term.source_locator, note: term.note
  }
]);
const exportData = {
  entries,
  topics: Object.fromEntries(source.topics.map(topic => [topic.id, topic.name])),
  sources: Object.fromEntries(source.sources.map(item => [item.id, item]))
};
try {
  rmSync(tempSqlite, { force: true });
  database.prepare('VACUUM INTO ?').run(tempSqlite);
  writeFileSync(tempScript, '// Generated by database/build.mjs\nwindow.LatinLexicon = ' + JSON.stringify(exportData) + ';\n');
  renameSync(tempSqlite, sqlitePath);
  renameSync(tempScript, scriptPath);
} finally {
  database.close();
  rmSync(tempSqlite, { force: true });
  rmSync(tempScript, { force: true });
}
console.log('Exported ' + entries.length + ' articles.');
